#!/usr/bin/env node

import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const ENGINE_COMPATIBILITY_ROOTS = Object.freeze([
  "src/domain/workflow.js",
  "src/engine/runtimeCompatibility.js",
]);

export const DEFAULT_ENGINE_COMPATIBILITY_PATH = path.join(
  root,
  "src",
  "engine",
  "generated",
  "compatibility.generated.js",
);

const LOCAL_IMPORT_PATTERN =
  /(?:import|export)\s+(?:[^"'`]*?\s+from\s+)?["'](\.{1,2}\/[^"']+)["']/gu;

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function resolveLocalImport(importer, specifier) {
  const candidate = path.resolve(path.dirname(importer), specifier);
  for (const resolved of [candidate, `${candidate}.js`, `${candidate}.jsx`]) {
    if (existsSync(resolved)) return resolved;
  }
  throw new Error(`Could not resolve compatibility input ${specifier} from ${importer}.`);
}

export function collectEngineCompatibilityInputs({
  rootDirectory = root,
  roots = ENGINE_COMPATIBILITY_ROOTS,
  readSource = (filePath) => readFileSync(filePath, "utf8"),
} = {}) {
  const pending = roots.map((relative) => path.resolve(rootDirectory, relative));
  const seen = new Map();

  while (pending.length > 0) {
    const absolute = pending.pop();
    if (seen.has(absolute)) continue;
    const relative = path.relative(rootDirectory, absolute).split(path.sep).join("/");
    if (relative.startsWith("../") || path.isAbsolute(relative)) {
      throw new Error(`Compatibility input escapes the repository: ${absolute}`);
    }
    const source = readSource(absolute);
    seen.set(absolute, source);

    for (const match of source.matchAll(LOCAL_IMPORT_PATTERN)) {
      const imported = resolveLocalImport(absolute, match[1]);
      const importedRelative = path.relative(rootDirectory, imported).split(path.sep).join("/");
      if (!importedRelative.startsWith("src/")) {
        throw new Error(`Compatibility input must remain under src/: ${importedRelative}`);
      }
      pending.push(imported);
    }
  }

  return [...seen.entries()]
    .map(([absolute, source]) => ({
      path: path.relative(rootDirectory, absolute).split(path.sep).join("/"),
      sha256: sha256(source),
      source,
    }))
    .sort((left, right) => left.path.localeCompare(right.path));
}

export function buildEngineCompatibility(options = {}) {
  const inputs = collectEngineCompatibilityInputs(options);
  const digest = sha256(
    inputs.map((input) => `${input.path}\0${input.sha256}\n`).join(""),
  );
  return {
    schemaVersion: 1,
    version: `digest-${digest.slice(0, 16)}`,
    hash: `sha256:${digest}`,
    inputs: inputs.map(({ path: inputPath, sha256: inputDigest }) => ({
      path: inputPath,
      sha256: inputDigest,
    })),
  };
}

export function buildGeneratedEngineCompatibilityModule(options = {}) {
  const manifest = buildEngineCompatibility(options);
  return `// Generated by scripts/build-engine-compatibility.mjs. Do not edit by hand.\n\nconst inputs = ${JSON.stringify(manifest.inputs, null, 2)}.map(Object.freeze);\n\nexport const engineCompatibility = Object.freeze({\n  schemaVersion: ${manifest.schemaVersion},\n  version: ${JSON.stringify(manifest.version)},\n  hash: ${JSON.stringify(manifest.hash)},\n  inputs: Object.freeze(inputs),\n});\n`;
}

export function generateEngineCompatibility({
  outputPath = DEFAULT_ENGINE_COMPATIBILITY_PATH,
  check = false,
  ...options
} = {}) {
  const generated = buildGeneratedEngineCompatibilityModule(options);
  if (check) {
    if (!existsSync(outputPath)) {
      throw new Error(`Missing generated engine compatibility module: ${outputPath}`);
    }
    if (readFileSync(outputPath, "utf8") !== generated) {
      throw new Error(
        "Generated engine compatibility identity is stale. Run npm run compatibility:generate and review the diff.",
      );
    }
  } else {
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, generated);
  }
  return buildEngineCompatibility(options);
}

export function main(args = process.argv.slice(2)) {
  const allowed = new Set(["--check"]);
  const unknown = args.filter((argument) => !allowed.has(argument));
  if (unknown.length > 0) throw new Error(`Unknown argument(s): ${unknown.join(", ")}`);
  const check = args.includes("--check");
  const manifest = generateEngineCompatibility({ check });
  console.log(
    `${check ? "Verified" : "Generated"} ${path.relative(root, DEFAULT_ENGINE_COMPATIBILITY_PATH)} (${manifest.hash})`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
